function Think()
    local bot = GetBot()
    assert(GetTeamMember(1) == bot)
    assert(GetSelectedHeroName(0) == 'npc_dota_hero_nevermore')
    assert(DotaTime() < 0 and GameTime() == RealTime())
    assert(GetUnitToUnitDistance(bot,bot) == 0)
    assert(bot:IsHero() and bot:CanBeSeen() and not bot:IsNull())
    assert(bot:GetGold() > 0 and bot:GetRespawnTime() == 0)
    assert(bot:GetActiveMode() == BOT_MODE_NONE and bot:GetActiveModeDesire() == 0)
    bot:SetTarget(bot)
    assert(bot:GetTarget() == bot)
    bot:SetNextItemPurchaseValue(50)
    assert(bot:GetNextItemPurchaseValue() == 50)
    assert(GetItemCost('item_branches') == __ITEM_COST__)
    assert(Clamp(2,0,1) == 1 and RemapValClamped(0.5,0,1,0,10) == 5)
    local ability = bot:GetAbilityByName('nevermore_shadowraze1')
    assert(ability ~= nil and ability:GetName() == 'nevermore_shadowraze1')
    assert(ability:GetLevel() == 0 and ability:CanAbilityBeUpgraded())
    assert(not ability:IsFullyCastable())
    bot:ActionImmediate_LevelAbility(ability:GetName())
    bot:ActionImmediate_PurchaseItem('item_branches')
end
