//! Numeric unit and ability rows of Roshan, from the same install as the items.
use heatel::keyvalues::{Kv, parse_kv, text};
use heatel::{DirSource, Vpk};
use std::{fmt::Write, path::Path};

pub fn table(dota: Option<&Path>) -> Result<String, String> {
    let game = crate::install::game_dir(dota)?;
    let build = crate::install::build(&game.join("steam.inf"))?;
    let source = DirSource::new(&game);
    let package = Vpk::open(&source, "pak01_dir.vpk").map_err(|e| e.to_string())?;
    let read = |path| -> Result<Kv, String> {
        let bytes = package
            .read_file(&source, path)
            .map_err(|e| e.to_string())?;
        parse_kv(text(&bytes).map_err(|e| e.to_string())?).map_err(|e| e.to_string())
    };
    let units = read("scripts/npc/npc_units.txt")?;
    let unit = units
        .get("DOTAUnits")
        .and_then(|root| root.get("npc_dota_roshan"))
        .ok_or("no Roshan unit")?;
    let mut out = format!(
        "//! Generated by `tools/import_items` from the installed Dota scripts and patch notes.\n\
         //! Internal keys and numeric values only. Run the importer to update.\n\
         //! Read from {build}.\nuse crate::{{Dec, ScriptData}};\n"
    );
    let (_, notes) = crate::install::read_patch_notes(dota)?;
    let team_gold = roshan_team_gold(&notes)?;
    writeln!(&mut out, "pub const ROSHAN_TEAM_GOLD: i32 = {team_gold};")
        .expect("write to a String");
    crate::emit::script_row(&mut out, "ROSHAN_UNIT", "npc_dota_roshan", unit)?;
    let banner = units
        .get("DOTAUnits")
        .and_then(|u| u.get("npc_dota_unit_roshans_banner"))
        .ok_or("no banner unit")?;
    crate::emit::script_row(
        &mut out,
        "BANNER_UNIT",
        "npc_dota_unit_roshans_banner",
        banner,
    )?;
    let abilities = read("scripts/npc/npc_abilities.txt")?;
    for (constant, key) in [
        ("ROSHAN_DEVOTION", "roshan_devotion"),
        ("ROSHAN_INHERENT_BUFFS", "roshan_inherent_buffs"),
        ("ROSHAN_SPELL_BLOCK", "roshan_spell_block"),
        ("ROSHAN_BASH", "roshan_bash"),
        ("ROSHAN_SLAM", "roshan_slam"),
        ("ROSHAN_REVENGEROAR", "roshan_revengeroar"),
        ("ROSHAN_GRAB", "roshan_grab_and_throw"),
    ] {
        let ability = abilities
            .get("DOTAAbilities")
            .and_then(|a| a.get(key))
            .ok_or("missing boss passive")?;
        let extra: Vec<(&str, &str)> = crate::neutral_overrides::ability_numbers(key)
            .map(|number| (number.name, number.levels))
            .collect();
        crate::emit::script_row_with(&mut out, constant, key, ability, &extra)?;
    }
    Ok(out)
}

// The unit row has the last-hitter's gold range. The installed note names
// the separate fixed payment to everyone on the killing team.
fn roshan_team_gold(notes: &Kv) -> Result<u16, String> {
    const KEY: &str = "DOTA_Patch_7_42_General_Global_Mechanics_21";
    let Some(Kv::Text(note)) = notes.get("patch").and_then(|rows| rows.get(KEY)) else {
        return Err(format!("patch notes: missing text row {KEY}"));
    };
    note.strip_prefix("Roshan gold per player decreased from ")
        .and_then(|wording| wording.split_once(" to "))
        .and_then(|(previous, current)| {
            previous.parse::<u16>().ok()?;
            current.parse::<u16>().ok()
        })
        .ok_or_else(|| format!("patch notes: {KEY} must give the old and new Roshan team awards"))
}

#[cfg(test)]
mod tests {
    #[test]
    #[ignore = "reads the installed patched game"]
    fn the_boss_table_includes_the_installed_team_award() {
        let table = super::table(None).expect("the preserved 7.42 tables");
        assert!(
            table
                .lines()
                .any(|line| line == "pub const ROSHAN_TEAM_GOLD: i32 = 125;")
        );
    }
}
