//! The committed hero table, as Rust source: one `HeroData` const a hero, then one
//! `AbilityData` const an ability, in slot order, then each generic talent's.

use std::fmt::Write;

use crate::ability::{Ability, Bonus, Kind};
use crate::dec::Milli;
use crate::emit::{BUILD_LINE, decimal};
use crate::hero::{self, Hero};
use crate::install::HeroSource;
use crate::overrides::PATCH;

/// The source of `crates/bota_core/src/heroes_data.rs` for the heroes of `source`.
pub fn table(source: &HeroSource) -> Result<String, String> {
    let heroes: Vec<Hero> = source
        .keys()
        .map(|key| hero::read(source, key))
        .collect::<Result<_, _>>()?;
    let mut out = header(&source.build, &heroes);
    let mut written: Vec<&str> = Vec::new();
    for hero in &heroes {
        write_hero(&mut out, hero)?;
        for ability in hero.abilities.iter().chain(&hero.shared_talents) {
            if written.contains(&ability.key.as_str()) {
                continue;
            }
            written.push(&ability.key);
            write_ability(&mut out, ability)?;
        }
    }
    let rows = |keys: &mut dyn Iterator<Item = &str>| -> String {
        keys.map(|key| format!("&{}", key.to_uppercase()))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let _ = write!(
        out,
        "\n/// Every hero row above.\npub(crate) const HERO_ROWS: &[&HeroData] = &[{}];\n\n/// \
         Every ability row above.\npub(crate) const ABILITY_ROWS: &[&AbilityData] = &[{}];\n",
        rows(&mut heroes.iter().map(|hero| hero.key.as_str())),
        rows(&mut written.iter().copied()),
    );
    Ok(out)
}

fn header(build: &str, heroes: &[Hero]) -> String {
    let names: Vec<String> = heroes.iter().map(|h| format!("`{}`", h.key)).collect();
    format!(
        "//! Every hero bota imports as Dota's `scripts/npc/heroes/` have it, over \
         `npc_dota_hero_base`,\n//! with its abilities and its generic talents' rows of \
         `scripts/npc/npc_abilities.txt`, at Dota\n//! {PATCH}'s numbers: Dota's internal names \
         and numbers only. Generated by\n//! `tools/import_items`; do not edit, run the tool. \
         Imported: {}.\n//!\n{BUILD_LINE}{build}.\n\nuse bota_proto::{{Attribute, \
         DamageKind}};\n\nuse crate::{{\n    AbilityData, AbilityValue, Behavior as B, Bonus, \
         Dec, Dispel, HeroData, Ms, TargetFlags as F,\n    TargetTeam, UnitTargets as T,\n}};\n",
        names.join(", ")
    )
}

fn write_hero(out: &mut String, hero: &Hero) -> Result<(), String> {
    let number = |name: &str| -> Milli {
        hero.numbers
            .iter()
            .find(|(key, _)| *key == name)
            .map(|(_, n)| *n)
            .expect("every number of hero::NUMBERS is read")
    };
    let dec = |name: &str| format!("Dec::of(\"{}\")", decimal(number(name)));
    let secs = |name: &str| format!("Ms::secs(\"{}\")", decimal(number(name)));
    let whole = |name: &str| -> Result<String, String> {
        let n = number(name);
        if n % 1000 != 0 {
            return Err(format!("{}: {name} is no whole number", hero.key));
        }
        Ok((n / 1000).to_string())
    };
    let primary = match hero.primary {
        "STRENGTH" => "Strength",
        "AGILITY" => "Agility",
        "INTELLECT" => "Intelligence",
        other => return Err(format!("{}: AttributePrimary {other}", hero.key)),
    };
    let quoted = |keys: &mut dyn Iterator<Item = &str>| -> String {
        keys.map(|k| format!("\"{k}\""))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let _ = write!(
        out,
        "\npub(crate) const {name}: HeroData = HeroData {{\n    key: \"{key}\",\n    \
         primary: Attribute::{primary},\n    strength: {str},\n    strength_gain: {str_gain},\n    \
         agility: {agi},\n    agility_gain: {agi_gain},\n    intelligence: {int},\n    \
         intelligence_gain: {int_gain},\n    armor: {armor},\n    magic_resist: {resist},\n    \
         melee: {melee},\n    damage_min: {dmin},\n    damage_max: {dmax},\n    \
         attack_rate: {rate},\n    attack_point: {point},\n    attack_range: {range},\n    \
         acquisition: {acq},\n    projectile_speed: {proj},\n    health: {hp},\n    \
         health_regen: {hp_regen},\n    mana: {mana},\n    mana_regen: {mana_regen},\n    \
         move_speed: {speed},\n    turn_rate: {turn},\n    day_vision: {day},\n    \
         night_vision: {night},\n    abilities: &[{abilities}],\n    talents: [{talents}],\n}};\n",
        name = hero.key.to_uppercase(),
        key = hero.key,
        str = dec("AttributeBaseStrength"),
        str_gain = dec("AttributeStrengthGain"),
        agi = dec("AttributeBaseAgility"),
        agi_gain = dec("AttributeAgilityGain"),
        int = dec("AttributeBaseIntelligence"),
        int_gain = dec("AttributeIntelligenceGain"),
        armor = dec("ArmorPhysical"),
        resist = dec("MagicalResistance"),
        melee = hero.melee,
        dmin = whole("AttackDamageMin")?,
        dmax = whole("AttackDamageMax")?,
        rate = secs("AttackRate"),
        point = secs("AttackAnimationPoint"),
        range = whole("AttackRange")?,
        acq = whole("AttackAcquisitionRange")?,
        proj = whole("ProjectileSpeed")?,
        hp = whole("StatusHealth")?,
        hp_regen = dec("StatusHealthRegen"),
        mana = whole("StatusMana")?,
        mana_regen = dec("StatusManaRegen"),
        speed = whole("MovementSpeed")?,
        turn = dec("MovementTurnRate"),
        day = whole("VisionDaytimeRange")?,
        night = whole("VisionNighttimeRange")?,
        abilities = quoted(&mut hero.abilities.iter().map(|a| a.key.as_str())),
        talents = quoted(&mut hero.talents.iter().map(String::as_str)),
    );
    Ok(())
}

fn write_ability(out: &mut String, ability: &Ability) -> Result<(), String> {
    let fail = |why: String| format!("{}: {why}", ability.key);
    let flags = |names: &[&str], prefix: &str, none: &str| -> String {
        match names.split_first() {
            None => none.to_owned(),
            Some((first, rest)) => {
                let rest: String = rest
                    .iter()
                    .map(|f| format!(".and({prefix}::{f})"))
                    .collect();
                format!("{prefix}::{first}{rest}")
            }
        }
    };
    let decs = |levels: &[Milli]| -> String {
        let all: Vec<String> = levels
            .iter()
            .map(|v| format!("Dec::of(\"{}\")", decimal(*v)))
            .collect();
        format!("&[{}]", all.join(", "))
    };
    let spans = |levels: &[Milli]| -> String {
        let all: Vec<String> = levels
            .iter()
            .map(|v| format!("Ms::secs(\"{}\")", decimal(*v)))
            .collect();
        format!("&[{}]", all.join(", "))
    };
    let wholes = |name: &str, levels: &[Milli]| -> Result<String, String> {
        let all = levels
            .iter()
            .map(|v| {
                (v % 1000 == 0)
                    .then(|| (v / 1000).to_string())
                    .ok_or_else(|| fail(format!("{name} is no whole number")))
            })
            .collect::<Result<Vec<_>, _>>()?;
        Ok(format!("&[{}]", all.join(", ")))
    };
    let option = |value: Option<String>| value.map_or("None".to_owned(), |v| format!("Some({v})"));
    let damage = ability.damage.map(|d| match d {
        "MAGICAL" => "DamageKind::Magical".to_owned(),
        "PHYSICAL" => "DamageKind::Physical".to_owned(),
        _ => "DamageKind::Pure".to_owned(),
    });
    let dispel = match ability.dispel {
        None => "Dispel::Unstated",
        Some("NO") => "Dispel::No",
        Some("YES") => "Dispel::Basic",
        Some(_) => "Dispel::Strong",
    };
    let team = ability.target_team.map(|t| match t {
        "ENEMY" => "TargetTeam::Enemy".to_owned(),
        "FRIENDLY" => "TargetTeam::Friendly".to_owned(),
        _ => "TargetTeam::Both".to_owned(),
    });
    let _ = write!(
        out,
        "\npub(crate) const {name}: AbilityData = AbilityData {{\n    key: \"{key}\",\n    \
         behavior: {behavior},\n    ultimate: {ultimate},\n    innate: {innate},\n    \
         max_level: {max_level},\n    cast_point: {point},\n    cast_range: {range},\n    \
         channel: {channel},\n    cooldown: {cooldown},\n    mana: {mana},\n    \
         damage: {damage},\n    pierces_immunity: {pierces:?},\n    dispel: {dispel},\n    \
         target_team: {team},\n    target_types: {types},\n    target_flags: {target_flags},\n",
        name = ability.key.to_uppercase(),
        key = ability.key,
        behavior = flags(&ability.behavior, "B", "B::NONE"),
        ultimate = ability.kind == Kind::Ultimate,
        innate = ability.innate,
        max_level = ability.max_level,
        point = spans(&ability.cast_point),
        range = wholes("AbilityCastRange", &ability.cast_range)?,
        channel = spans(&ability.channel),
        cooldown = spans(&ability.cooldown),
        mana = wholes("AbilityManaCost", &ability.mana)?,
        damage = option(damage),
        pierces = ability.pierces_immunity,
        dispel = dispel,
        team = option(team),
        types = flags(&ability.target_types, "T", "T::NONE"),
        target_flags = flags(&ability.target_flags, "F", "F::NONE"),
    );
    if ability.values.is_empty() {
        out.push_str("    values: &[],\n};\n");
        return Ok(());
    }
    out.push_str("    values: &[\n");
    for value in &ability.values {
        let bonuses: Vec<String> = value
            .bonuses
            .iter()
            .map(|(key, bonus)| {
                let bonus = match bonus {
                    Bonus::Add(levels) => format!("Bonus::Add({})", decs(levels)),
                    Bonus::Times(factor) => {
                        format!("Bonus::Times(Dec::of(\"{}\"))", decimal(*factor))
                    }
                    Bonus::Set(levels) => format!("Bonus::Set({})", decs(levels)),
                    Bonus::Percent(pct) => {
                        format!("Bonus::Percent(Dec::of(\"{}\"))", decimal(*pct))
                    }
                };
                format!("(\"{key}\", {bonus})")
            })
            .collect();
        let _ = writeln!(
            out,
            "        AbilityValue {{\n            name: \"{}\",\n            levels: {},\n            \
             bonuses: &[{}],\n        }},",
            value.name,
            decs(&value.levels),
            bonuses.join(", ")
        );
    }
    out.push_str("    ],\n};\n");
    Ok(())
}
