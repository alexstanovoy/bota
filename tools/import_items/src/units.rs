//! Numeric rows of the units bota builds from `npc_units.txt` besides heroes, lane creeps and
//! Roshan: the courier and the two wards, whose pip health is their `StatusHealth`.
use heatel::keyvalues::{parse_kv, text};
use heatel::{DirSource, Vpk};
use std::path::Path;

/// Each row's constant and the unit it is read from.
const UNITS: [(&str, &str); 3] = [
    ("COURIER_UNIT", "npc_dota_courier"),
    ("OBSERVER_WARD_UNIT", "npc_dota_observer_wards"),
    ("SENTRY_WARD_UNIT", "npc_dota_sentry_wards"),
];

pub fn table(dota: Option<&Path>) -> Result<String, String> {
    let game = crate::install::game_dir(dota)?;
    let build = crate::install::build(&game.join("steam.inf"))?;
    let source = DirSource::new(&game);
    let package = Vpk::open(&source, "pak01_dir.vpk").map_err(|e| e.to_string())?;
    let bytes = package
        .read_file(&source, "scripts/npc/npc_units.txt")
        .map_err(|e| e.to_string())?;
    let units = parse_kv(text(&bytes).map_err(|e| e.to_string())?).map_err(|e| e.to_string())?;
    let mut out = format!(
        "//! Generated by `tools/import_items` from the installed Dota scripts.\n\
         //! Internal keys and numeric values only. Run the importer to update.\n\
         //! Read from {build}.\nuse crate::{{Dec, ScriptData}};\n"
    );
    for (constant, key) in UNITS {
        let unit = units
            .get("DOTAUnits")
            .and_then(|root| root.get(key))
            .ok_or(format!("npc_units.txt: no {key}"))?;
        crate::emit::script_row(&mut out, constant, key, unit)?;
    }
    Ok(out)
}
