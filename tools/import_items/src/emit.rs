//! The committed table, as Rust source: one `ItemData` const an item, in registry order.

use std::fmt::Write;

use heatel::keyvalues::Kv;

use crate::dec::Milli;
use crate::install::Source;
use crate::item::{self, Item};
use crate::overrides::{self, OVERRIDES, PATCH};
use crate::registry::Registered;

/// How the line naming the client build the table was read from starts.
pub const BUILD_LINE: &str = "//! Read from ";

/// Whether two tables hold the same rows: the same text but for the client
/// build each was read from, so an install updated without a change to the
/// rows still agrees with the table.
pub fn same_items(one: &str, other: &str) -> bool {
    let items = |table: &str| {
        table
            .lines()
            .filter(|line| !line.starts_with(BUILD_LINE))
            .map(str::to_owned)
            .collect::<Vec<_>>()
    };
    items(one) == items(other)
}

/// The source of `crates/bota_core/src/data/items.rs` for the registered items.
pub fn table(source: &Source, registered: &[Registered]) -> Result<String, String> {
    let items = source.items();
    // An item the game no longer lists keeps its row and its id, holding nothing and offered
    // nowhere: its rules stay, to be offered again.
    let gone = heatel::keyvalues::Kv::Block(Default::default());
    let mut rows = Vec::with_capacity(registered.len());
    for entry in registered {
        let listed = items.get(&entry.key);
        if listed.is_none() && !entry.retired {
            println!(
                "import_items: {} is no longer in items.txt: its row stays, not purchasable",
                entry.key
            );
        }
        let mut row = item::read(&entry.key, listed.unwrap_or(&gone))?;
        if listed.is_none() {
            row.purchasable = false;
        }
        overrides::apply(&mut row)?;
        rows.push(row);
    }
    for o in OVERRIDES {
        if !registered.iter().any(|entry| entry.key == o.item) {
            return Err(format!(
                "an override names {}, which bota does not carry",
                o.item
            ));
        }
    }
    let mut out = header(&source.build);
    for (entry, row) in registered.iter().zip(&rows) {
        let builds = builds(items, registered, &row.key)?;
        write_row(&mut out, entry, row, &builds);
    }
    Ok(out)
}

fn header(build: &str) -> String {
    let mut out = format!(
        "//! Every item bota carries as Dota's `scripts/npc/items.txt` has it, at Dota {PATCH}'s \
         numbers:\n//! Dota's internal names and numbers only. Generated by `tools/import_items`; \
         do not edit, run\n//! the tool.\n//!\n{BUILD_LINE}{build}.\n"
    );
    if !OVERRIDES.is_empty() {
        out.push_str(&format!(
            "//!\n//! Where {PATCH} is not the install (`tools/import_items/src/overrides.rs`):\n"
        ));
        for o in OVERRIDES {
            let _ = writeln!(
                out,
                "//! - `{}` {:?} {}: {}",
                o.item, o.field, o.value, o.evidence
            );
        }
    }
    out.push_str(
        "\nuse bota_proto::ItemId;\n\nuse crate::{Behavior as B, Dec, Dispel, Immunity, ItemData, ItemLimits, Ms, StockData};\n",
    );
    out
}

/// The ways `result` is built, each a list of item ids: a recipe's requirements, and the recipe
/// scroll itself where it costs gold. Every part must be registered.
fn builds(items: &Kv, registered: &[Registered], result: &str) -> Result<Vec<Vec<u16>>, String> {
    let id_of = |key: &str| {
        registered
            .iter()
            .find(|entry| entry.key == key)
            .map(|entry| entry.id)
            .ok_or(format!(
                "{result} is built of {key}, which bota does not carry: register it"
            ))
    };
    let mut ways = Vec::new();
    for (key, block) in items.block().unwrap_or(&[]) {
        let made_here =
            matches!(block.get("ItemResult"), Some(Kv::Text(made)) if made.trim() == result);
        if !made_here {
            continue;
        }
        let recipe = item::read(key, block)?;
        let Some((made, requirements)) = &recipe.recipe else {
            continue;
        };
        if made != result {
            continue;
        }
        for parts in requirements {
            let mut way: Vec<u16> = parts
                .iter()
                .map(|part| id_of(part))
                .collect::<Result<_, _>>()?;
            if recipe.cost > 0 {
                way.push(id_of(key)?);
            }
            ways.push(way);
        }
    }
    Ok(ways)
}

fn write_row(out: &mut String, entry: &Registered, row: &Item, builds: &[Vec<u16>]) {
    let behavior = if row.behavior.is_empty() {
        "B::NONE".to_owned()
    } else {
        let rest: String = row.behavior[1..]
            .iter()
            .map(|f| format!(".and(B::{f})"))
            .collect();
        format!("B::{}{rest}", row.behavior[0])
    };
    let stock = row.stock.map_or("None".to_owned(), |(initial, max, every, opens)| {
        format!(
            "Some(StockData {{\n        initial: {initial},\n        max: {max},\n        every: {},\n        \
             opens: {},\n    }})",
            secs(every),
            secs(opens)
        )
    });
    let _ = write!(
        out,
        "\npub(crate) const {name}: ItemData = ItemData {{\n    id: ItemId({id}),\n    key: \"{key}\",\n    \
         retired: {retired},\n    cost: {cost},\n    behavior: {behavior},\n    cast_range: {range},\n    \
         cast_point: {point},\n    channel: {channel},\n    cooldown: {cooldown},\n    mana: {mana},\n    \
         health: {health},\n    charges: {charges},\n    stack: {stack},\n    stock: {stock},\n    \
         purchasable: {purchasable},\n    secret_shop: {secret_shop},\n    dispel: {dispel},\n    \
         immunity: {immunity},\n",
        name = row.key.to_uppercase(),
        id = entry.id,
        key = row.key,
        retired = entry.retired,
        cost = row.cost,
        range = row.cast_range,
        point = secs(row.cast_point),
        channel = secs(row.channel),
        cooldown = secs(row.cooldown),
        mana = row.mana,
        health = row.health,
        secret_shop = row.secret_shop,
        dispel = match row.dispel {
            None => "Dispel::Unstated",
            Some("NO") => "Dispel::No",
            Some("YES") => "Dispel::Basic",
            Some(_) => "Dispel::Strong",
        },
        immunity = match row.immunity {
            None => "Immunity::Unstated",
            Some("ENEMIES_NO") => "Immunity::Blocks",
            Some(_) => "Immunity::Pierced",
        },
        charges = row.charges,
        stack = match (row.stackable, row.stack_max) {
            (false, _) => "0".to_owned(),
            (true, None) => "u8::MAX".to_owned(),
            (true, Some(max)) => max.to_string(),
        },
        purchasable = row.purchasable,
    );
    let _ = writeln!(
        out,
        "    limits: ItemLimits {{ droppable: {}, sellable: {}, killable: {}, backpack: {}, \
         used_from_backpack: {} }},",
        row.droppable, row.sellable, row.killable, row.backpack, row.used_from_backpack
    );
    let _ = writeln!(
        out,
        "    cooldown_in_inventory: {},",
        row.cooldown_in_inventory
    );
    let ways: Vec<String> = builds
        .iter()
        .map(|way| {
            let ids: Vec<String> = way.iter().map(|id| format!("ItemId({id})")).collect();
            format!("&[{}]", ids.join(", "))
        })
        .collect();
    let _ = writeln!(out, "    builds: &[{}],", ways.join(", "));
    let aoe: Vec<String> = row.aoe.iter().map(|key| format!("\"{key}\"")).collect();
    let _ = writeln!(out, "    aoe: &[{}],", aoe.join(", "));
    let potency: Vec<String> = row.potency.iter().map(|key| format!("\"{key}\"")).collect();
    let _ = writeln!(out, "    potency: &[{}],", potency.join(", "));
    let shared = row
        .shared_cooldown
        .as_ref()
        .map_or("None".to_owned(), |name| format!("Some(\"{name}\")"));
    let _ = writeln!(out, "    shared_cooldown: {shared},");
    if row.values.is_empty() {
        out.push_str("    values: &[],\n};\n");
        return;
    }
    out.push_str("    values: &[\n");
    for (name, levels) in &row.values {
        let levels: Vec<String> = levels
            .iter()
            .map(|v| format!("Dec::of(\"{}\")", decimal(*v)))
            .collect();
        let _ = writeln!(out, "        (\"{name}\", &[{}]),", levels.join(", "));
    }
    out.push_str("    ],\n};\n");
}

/// Seconds as a script writes them.
fn secs(milli: Milli) -> String {
    format!("Ms::secs(\"{}\")", decimal(milli))
}

/// The shortest decimal of a number in thousandths: `250` is `0.25`.
pub fn decimal(milli: Milli) -> String {
    let sign = if milli < 0 { "-" } else { "" };
    let (whole, fraction) = (milli.abs() / 1000, milli.abs() % 1000);
    if fraction == 0 {
        format!("{sign}{whole}")
    } else {
        let digits = format!("{fraction:03}");
        format!("{sign}{whole}.{}", digits.trim_end_matches('0'))
    }
}

pub(crate) fn script_row(
    out: &mut String,
    constant: &str,
    key: &str,
    block: &Kv,
) -> Result<(), String> {
    script_row_with(out, constant, key, block, &[])
}

/// As [`script_row`], with `extra` numbers (a name and its levels as a script writes them) that
/// the script does not hold: none may be one it holds.
pub(crate) fn script_row_with(
    out: &mut String,
    constant: &str,
    key: &str,
    block: &Kv,
    extra: &[(&str, &str)],
) -> Result<(), String> {
    let mut fields = Vec::new();
    for (key, value) in block.block().ok_or("not a block")? {
        if let Kv::Text(text) = value
            && let Ok(values) = crate::dec::levels(text)
        {
            fields.push((key.clone(), values));
        }
    }
    fields.extend(crate::item::values(block)?);
    for (name, levels) in extra {
        if fields.iter().any(|(held, _)| held == name) {
            return Err(format!(
                "override of {key} {name}: the install holds it already: drop the override"
            ));
        }
        fields.push(((*name).to_owned(), crate::dec::levels(levels)?));
    }
    let _ = writeln!(
        out,
        "pub const {constant}: ScriptData = ScriptData {{ key: {key:?}, values: &["
    );
    for (name, values) in fields {
        let _ = write!(out, "({name:?}, &[");
        for value in values {
            let value =
                i32::try_from(value).map_err(|_| format!("{key}.{name}: number out of range"))?;
            let _ = write!(out, "Dec({value}),");
        }
        out.push_str("]),\n");
    }
    out.push_str("] };\n");
    Ok(())
}

#[cfg(test)]
mod tests {
    use crate::install::Source;
    use crate::registry::Registered;

    /// An item the game stops listing (7.42's Revenant's Brooch recipe) keeps its row and its id
    /// in the table, and is offered nowhere: not purchasable, not at cost 0.
    #[test]
    fn an_item_the_install_no_longer_lists_keeps_a_row_nobody_can_buy() {
        let source = Source::new(
            "fixture".into(),
            // The ward dispenser stands in for every row the overrides name.
            r#""DOTAAbilities" { "item_kept" { "ItemCost" "50" }
                "item_ward_dispenser" { "ItemCost" "0" "AbilityCooldown" "0" } }"#,
        )
        .expect("KV");
        let registered = [
            Registered {
                id: 0,
                key: "item_kept".into(),
                retired: false,
            },
            Registered {
                id: 2,
                key: "item_ward_dispenser".into(),
                retired: false,
            },
            Registered {
                id: 1,
                key: "item_gone".into(),
                retired: false,
            },
        ];
        let table = super::table(&source, &registered).unwrap_or_else(|why| panic!("{why}"));
        let row = |key: &str| {
            table
                .split("ItemData = ItemData {")
                .find(|row| row.contains(&format!("key: \"{key}\"")))
                .expect("its row")
                .to_owned()
        };
        assert!(row("item_kept").contains("purchasable: true"));
        assert!(row("item_gone").contains("purchasable: false"));
        assert!(
            row("item_gone").contains("retired: false"),
            "its id stays live"
        );
    }
}
