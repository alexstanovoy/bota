//! The committed table, as Rust source: one `ItemData` const an item, in registry order.

use std::fmt::Write;

use heatel::keyvalues::Kv;

use crate::dec::Milli;
use crate::install::Source;
use crate::item::{self, Item};
use crate::overrides::{self, OVERRIDES, PATCH};
use crate::registry::Registered;

/// The source of `crates/bota_core/src/data/items.rs` for the registered items.
pub fn table(source: &Source, registered: &[Registered]) -> Result<String, String> {
    let items = source.items();
    let mut rows = Vec::with_capacity(registered.len());
    for entry in registered {
        let block = items
            .get(&entry.key)
            .ok_or(format!("{} is registered but not in items.txt", entry.key))?;
        let mut row = item::read(&entry.key, block)?;
        overrides::apply(&mut row)?;
        rows.push(row);
    }
    for o in OVERRIDES {
        if !registered.iter().any(|entry| entry.key == o.item) {
            return Err(format!(
                "an override names {}, which bota does not carry",
                o.item
            ));
        }
    }
    let mut out = header(&source.build);
    for (entry, row) in registered.iter().zip(&rows) {
        let builds = builds(items, registered, &row.key)?;
        write_row(&mut out, entry, row, &builds);
    }
    Ok(out)
}

fn header(build: &str) -> String {
    let mut out = format!(
        "//! Every item bota carries as Dota's `scripts/npc/items.txt` has it, {build}, at Dota \
         {PATCH}'s\n//! numbers: Dota's internal names and numbers only. Generated by \
         `tools/import_items`; do not edit,\n//! run the tool.\n"
    );
    if !OVERRIDES.is_empty() {
        out.push_str(
            "//!\n//! Where 7.41f is not the install (`tools/import_items/src/overrides.rs`):\n",
        );
        for o in OVERRIDES {
            let _ = writeln!(
                out,
                "//! - `{}` {:?} {}: {}",
                o.item, o.field, o.value, o.evidence
            );
        }
    }
    out.push_str(
        "\nuse bota_proto::ItemId;\n\nuse crate::{Behavior as B, Dec, ItemData, Ms, StockData};\n",
    );
    out
}

/// The ways `result` is built, each a list of item ids: a recipe's requirements, and the recipe
/// scroll itself where it costs gold. Every part must be registered.
fn builds(items: &Kv, registered: &[Registered], result: &str) -> Result<Vec<Vec<u16>>, String> {
    let id_of = |key: &str| {
        registered
            .iter()
            .find(|entry| entry.key == key)
            .map(|entry| entry.id)
            .ok_or(format!(
                "{result} is built of {key}, which bota does not carry: register it"
            ))
    };
    let mut ways = Vec::new();
    for (key, block) in items.block().unwrap_or(&[]) {
        let made_here =
            matches!(block.get("ItemResult"), Some(Kv::Text(made)) if made.trim() == result);
        if !made_here {
            continue;
        }
        let recipe = item::read(key, block)?;
        let Some((made, requirements)) = &recipe.recipe else {
            continue;
        };
        if made != result {
            continue;
        }
        for parts in requirements {
            let mut way: Vec<u16> = parts
                .iter()
                .map(|part| id_of(part))
                .collect::<Result<_, _>>()?;
            if recipe.cost > 0 {
                way.push(id_of(key)?);
            }
            ways.push(way);
        }
    }
    Ok(ways)
}

fn write_row(out: &mut String, entry: &Registered, row: &Item, builds: &[Vec<u16>]) {
    let behavior = if row.behavior.is_empty() {
        "B::NONE".to_owned()
    } else {
        let rest: String = row.behavior[1..]
            .iter()
            .map(|f| format!(".and(B::{f})"))
            .collect();
        format!("B::{}{rest}", row.behavior[0])
    };
    let stock = row.stock.map_or("None".to_owned(), |(initial, max, every)| {
        format!(
            "Some(StockData {{\n        initial: {initial},\n        max: {max},\n        every: {},\n    }})",
            secs(every)
        )
    });
    let _ = write!(
        out,
        "\npub(crate) const {name}: ItemData = ItemData {{\n    id: ItemId({id}),\n    key: \"{key}\",\n    \
         retired: {retired},\n    cost: {cost},\n    behavior: {behavior},\n    cast_range: {range},\n    \
         cast_point: {point},\n    channel: {channel},\n    cooldown: {cooldown},\n    mana: {mana},\n    \
         health: {health},\n    charges: {charges},\n    stack: {stack},\n    stock: {stock},\n    \
         purchasable: {purchasable},\n",
        name = row.key.to_uppercase(),
        id = entry.id,
        key = row.key,
        retired = entry.retired,
        cost = row.cost,
        range = row.cast_range,
        point = secs(row.cast_point),
        channel = secs(row.channel),
        cooldown = secs(row.cooldown),
        mana = row.mana,
        health = row.health,
        charges = row.charges,
        stack = match (row.stackable, row.stack_max) {
            (false, _) => "0".to_owned(),
            (true, None) => "u8::MAX".to_owned(),
            (true, Some(max)) => max.to_string(),
        },
        purchasable = row.purchasable,
    );
    let ways: Vec<String> = builds
        .iter()
        .map(|way| {
            let ids: Vec<String> = way.iter().map(|id| format!("ItemId({id})")).collect();
            format!("&[{}]", ids.join(", "))
        })
        .collect();
    let _ = writeln!(out, "    builds: &[{}],", ways.join(", "));
    if row.values.is_empty() {
        out.push_str("    values: &[],\n};\n");
        return;
    }
    out.push_str("    values: &[\n");
    for (name, levels) in &row.values {
        let levels: Vec<String> = levels
            .iter()
            .map(|v| format!("Dec::of(\"{}\")", decimal(*v)))
            .collect();
        let _ = writeln!(out, "        (\"{name}\", &[{}]),", levels.join(", "));
    }
    out.push_str("    ],\n};\n");
}

/// Seconds as a script writes them.
fn secs(milli: Milli) -> String {
    format!("Ms::secs(\"{}\")", decimal(milli))
}

/// The shortest decimal of a number in thousandths: `250` is `0.25`.
fn decimal(milli: Milli) -> String {
    let sign = if milli < 0 { "-" } else { "" };
    let (whole, fraction) = (milli.abs() / 1000, milli.abs() % 1000);
    if fraction == 0 {
        format!("{sign}{whole}")
    } else {
        let digits = format!("{fraction:03}");
        format!("{sign}{whole}.{}", digits.trim_end_matches('0'))
    }
}
