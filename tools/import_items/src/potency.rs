//! The ordinary illusion and Illusion Rune potency values are absent from the numeric scripts.
//! The install ships both values in the localization keys for the patch that changed them.

use std::path::Path;

use heatel::keyvalues::Kv;

const ILLUSION: &str = "DOTA_Patch_7_42_General_Global_Mechanics_54";
const ILLUSION_RUNE: &str = "DOTA_Patch_7_42_General_Map_Objectives_20";

pub fn table(dota: Option<&Path>) -> Result<String, String> {
    let (build, notes) = crate::install::read_patch_notes(dota)?;
    let illusion = basis_points(&notes, ILLUSION)?;
    let rune = basis_points(&notes, ILLUSION_RUNE)?;
    Ok(format!(
        "//! Generated by `tools/import_items` from the installed patch-note rows.\n\
         //! Read from {build}.\n\n\
         pub(crate) const ILLUSION_BP: u16 = {illusion};\n\
         pub(crate) const ILLUSION_RUNE_BP: u16 = {rune};\n"
    ))
}

fn basis_points(notes: &Kv, key: &str) -> Result<u16, String> {
    let Some(Kv::Text(note)) = notes.get("patch").and_then(|rows| rows.get(key)) else {
        return Err(format!("patch notes: missing text row {key}"));
    };
    let mut percentages = note
        .split_ascii_whitespace()
        .filter_map(|word| word.strip_suffix('%'));
    let Some(percent) = percentages
        .next()
        .and_then(|value| value.parse::<u16>().ok())
        .filter(|&percent| percent <= 100)
    else {
        return Err(format!(
            "patch notes: {key} must give a percentage from 0 to 100"
        ));
    };
    if percentages.next().is_some() {
        return Err(format!("patch notes: {key} gives more than one percentage"));
    }
    Ok(percent * 100)
}
