//! Convex placement volumes from the installed map's entity physics.
use heatel::{DirSource, Resource, Vpk, find_game_dir, kv3::Value};
use std::{fmt::Write, path::Path};

type Point = (i32, i32);

#[derive(Default)]
struct Budget {
    models: usize,
    parts: usize,
    hulls: usize,
    vertices: usize,
}

pub fn table(dota: Option<&Path>) -> Result<String, String> {
    let game = find_game_dir(dota).ok_or("no Dota 2 install")?;
    let source = DirSource::new(game.join("maps"));
    let package = Vpk::open(&source, "dota.vpk").map_err(|e| e.to_string())?;
    let bytes = package
        .read_file(&source, "maps/dota/entities/default_ents.vents_c")
        .map_err(|e| e.to_string())?;
    let entities = Resource::parse(&bytes)
        .map_err(|e| e.to_string())?
        .data()
        .ok_or("no map entities")?
        .map_err(|e| e.to_string())?;
    let mut out = String::from(
        "//! Generated by `tools/import_items` from installed map entity physics.\nuse crate::PitZone;\nuse bota_proto::Vec2;\npub const DOTA_NO_WARDS: &[PitZone] = &[\n",
    );
    let mut budget = Budget::default();
    for entity in array(&entities, "m_entityKeyValues")? {
        let values = entity
            .get("keyValues3Data")
            .and_then(|v| v.get("values"))
            .ok_or("entity has no values")?;
        if values.get("classname").and_then(Value::as_str) != Some("trigger_no_wards") {
            continue;
        }
        if values.get("StartDisabled").and_then(Value::as_bool) != Some(false)
            || values.get("filtername").and_then(Value::as_str) != Some("")
        {
            return Err("conditional ward exclusion is unsupported".into());
        }
        emit_volume(&mut out, values, &source, &package, &mut budget)?;
    }
    if budget.hulls == 0 {
        return Err("no ward placement volumes".into());
    }
    out.push_str("];\n");
    Ok(out)
}

fn emit_volume(
    out: &mut String,
    values: &Value,
    source: &DirSource,
    package: &Vpk,
    budget: &mut Budget,
) -> Result<(), String> {
    budget.models += 1;
    if budget.models > 64 {
        return Err("too many ward exclusion models".into());
    }
    let origin = vector(values, "origin")?;
    let angles = vector(values, "angles")?;
    if angles[0] != 0. || angles[2] != 0. || vector(values, "scales")? != [1.; 3] {
        return Err("unsupported placement volume transform".into());
    }
    let model = values
        .get("model")
        .and_then(Value::as_str)
        .ok_or("no volume model")?;
    if model.len() > 256
        || !model.starts_with("maps/dota/entities/")
        || !model.ends_with(".vmdl")
        || !model
            .bytes()
            .all(|c| c.is_ascii_alphanumeric() || b"_/.-".contains(&c))
        || model.split('/').any(|part| part == "..")
    {
        return Err("invalid placement model path".into());
    }
    let bytes = package
        .read_file(source, &format!("{model}_c"))
        .map_err(|e| e.to_string())?;
    let physics = Resource::parse(&bytes)
        .map_err(|e| e.to_string())?
        .kv3(b"PHYS")
        .ok_or("volume has no physics")?
        .map_err(|e| e.to_string())?
        .root;
    let _ = writeln!(out, "// {model}");
    let before = budget.hulls;
    for part in array(&physics, "m_parts")? {
        budget.parts += 1;
        if budget.parts > 1024 {
            return Err("too many placement parts".into());
        }
        let shape = part.get("m_rnShape").ok_or("no volume shape")?;
        for key in ["m_spheres", "m_capsules", "m_meshes"] {
            if shape
                .get(key)
                .and_then(Value::as_array)
                .is_some_and(|v| !v.is_empty())
            {
                return Err(format!("unsupported placement shape {key}"));
            }
        }
        for hull in array(shape, "m_hulls")? {
            emit_hull(out, hull, origin, angles[1], budget)?;
        }
    }
    if budget.hulls == before {
        return Err("placement model has no convex hulls".into());
    }
    Ok(())
}

fn emit_hull(
    out: &mut String,
    hull: &Value,
    origin: [f64; 3],
    yaw: f64,
    budget: &mut Budget,
) -> Result<(), String> {
    budget.hulls += 1;
    if budget.hulls > 256 {
        return Err("too many placement hulls".into());
    }
    let raw = hull
        .get("m_Hull")
        .and_then(|v| v.get("m_VertexPositions"))
        .and_then(Value::as_blob)
        .ok_or("no hull vertices")?;
    if raw.len() % 12 != 0 || raw.len() > 12 * 4096 {
        return Err("bad hull vertex count".into());
    }
    budget.vertices += raw.len() / 12;
    if budget.vertices > 65536 {
        return Err("too many placement vertices".into());
    }
    let (sin, cos) = yaw.to_radians().sin_cos();
    let mut points = Vec::new();
    for vertex in raw.as_chunks::<12>().0 {
        let x = f64::from(f32::from_le_bytes(
            vertex[..4].try_into().expect("four bytes"),
        ));
        let y = f64::from(f32::from_le_bytes(
            vertex[4..8].try_into().expect("four bytes"),
        ));
        let (x, y) = (
            origin[0] + x * cos - y * sin + 9216.,
            origin[1] + x * sin + y * cos + 9216.,
        );
        if !x.is_finite() || !y.is_finite() || x.abs() > 32767. || y.abs() > 32767. {
            return Err("bad volume coordinate".into());
        }
        points.push((x.round() as i32, y.round() as i32));
    }
    let points = boundary(points);
    if points.len() < 3 {
        return Err("degenerate placement volume".into());
    }
    out.push_str("PitZone { corners: &[\n");
    for (x, y) in points {
        let _ = writeln!(out, "Vec2::from_ints({x}, {y}),");
    }
    out.push_str("] },\n");
    if out.len() > 4 * 1024 * 1024 {
        return Err("placement output is too large".into());
    }
    Ok(())
}

fn array<'a>(value: &'a Value, key: &str) -> Result<&'a [Value], String> {
    value
        .get(key)
        .and_then(Value::as_array)
        .filter(|a| a.len() <= 65536)
        .ok_or_else(|| format!("missing or excessive array {key}"))
}
fn vector(value: &Value, key: &str) -> Result<[f64; 3], String> {
    let values = array(value, key)?;
    if values.len() != 3 {
        return Err(format!("not a vector: {key}"));
    }
    let mut out = [0.; 3];
    for (out, value) in out.iter_mut().zip(values) {
        *out = value
            .as_f64()
            .filter(|n| n.is_finite())
            .ok_or("bad vector coordinate")?;
    }
    Ok(out)
}
fn cross(a: Point, b: Point, c: Point) -> i64 {
    i64::from(b.0 - a.0) * i64::from(c.1 - a.1) - i64::from(b.1 - a.1) * i64::from(c.0 - a.0)
}
fn boundary(mut points: Vec<Point>) -> Vec<Point> {
    points.sort_unstable();
    points.dedup();
    let mut hull = Vec::new();
    for half in [points.clone(), points.into_iter().rev().collect()] {
        let start = hull.len();
        for point in half {
            while hull.len() >= start + 2
                && cross(hull[hull.len() - 2], hull[hull.len() - 1], point) <= 0
            {
                hull.pop();
            }
            hull.push(point);
        }
        hull.pop();
    }
    hull
}
