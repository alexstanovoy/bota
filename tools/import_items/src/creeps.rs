//! Lane creep numeric rows from the same installed scripts as the item catalogue.
use heatel::keyvalues::{parse_kv, text};
use heatel::{DirSource, Vpk, find_game_dir};
use std::path::Path;

pub fn table(dota: Option<&Path>) -> Result<String, String> {
    let game = find_game_dir(dota).ok_or("no Dota 2 install")?;
    let build = crate::install::build(&game.join("steam.inf"))?;
    let source = DirSource::new(&game);
    let package = Vpk::open(&source, "pak01_dir.vpk").map_err(|e| e.to_string())?;
    let bytes = package
        .read_file(&source, "scripts/npc/npc_units.txt")
        .map_err(|e| e.to_string())?;
    let parsed = parse_kv(text(&bytes).map_err(|e| e.to_string())?).map_err(|e| e.to_string())?;
    let units = parsed.get("DOTAUnits").ok_or("no unit scripts")?;
    let mut out = format!(
        "//! Generated by `tools/import_items` from installed npc_units.txt.\n//! Numeric values and internal keys only.\n//! Read from {build}.\nuse crate::{{Dec, ScriptData}};\n"
    );
    for side in ["goodguys", "badguys"] {
        for kind in ["melee", "ranged", "siege"] {
            for tier in ["", "_upgraded", "_upgraded_mega"] {
                let key = if kind == "siege" {
                    format!("npc_dota_{side}_{kind}{tier}")
                } else {
                    format!("npc_dota_creep_{side}_{kind}{tier}")
                };
                let unit = units.get(&key).ok_or_else(|| format!("missing {key}"))?;
                let constant = format!("{side}_{kind}{tier}").to_uppercase();
                crate::emit::script_row(&mut out, &constant, &key, unit)?;
            }
        }
    }
    Ok(out)
}
