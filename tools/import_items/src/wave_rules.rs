//! The wave schedule and first Roshan bound are shipped as patch-note rows.

use std::path::Path;

use heatel::keyvalues::Kv;

const LANE: &str = "DOTA_Patch_7_42_General_Lane_Creeps__Towers_and_Bases";
const OBJECTIVES: &str = "DOTA_Patch_7_42_General_Map_Objectives";

pub fn table(dota: Option<&Path>) -> Result<String, String> {
    let capture_ignores_silence = crate::install::ability_has_behavior(
        dota,
        "ability_capture",
        "DOTA_ABILITY_BEHAVIOR_IGNORE_SILENCE",
    )?;
    let (build, notes) = crate::install::read_patch_notes(dota)?;
    let row = |prefix, index| text(&notes, &format!("{prefix}_{index}"));
    let melee_end = last_numbered_word(row(LANE, 2)?, "at ")?;
    let flag_every = last_numbered_word(row(LANE, 3)?, "after the ")?;
    let ranged_extra = last_numbered_word(row(LANE, 4)?, " to ")?;
    let siege_early = siege_row(row(LANE, 11)?)?;
    let siege_middle = siege_row(row(LANE, 12)?)?;
    let siege_late = siege_row(row(LANE, 13)?)?;
    let roshan = row(OBJECTIVES, 12)?;
    let decay = last_numbered_word(roshan, "decreases by ")?;
    let floor = last_numbered_word(roshan, "a minimum of ")?;

    Ok(format!(
        "//! Generated by `tools/import_items` from the installed patch-note and ability rows.\n\
         //! Read from {build}.\n\n\
         pub(crate) const OMITTED_MELEE_GROWTH_SECONDS: u32 = {};\n\
         pub(crate) const RANGED_GROWTH_SECONDS: u32 = {};\n\
         pub(crate) const FLAG_EVERY_WAVE_SECONDS: u32 = {};\n\
         pub(crate) const SIEGE: [(u32, u32, u32); 3] = [{siege_early:?}, {siege_middle:?}, {siege_late:?}];\n\
         pub(crate) const ROSHAN_RESPAWN_DECAY_SECONDS: u32 = {};\n\
         pub(crate) const ROSHAN_BASE_FLOOR_SECONDS: u32 = {};\n\
         pub(crate) const OUTPOST_CAPTURE_IGNORES_SILENCE: bool = {capture_ignores_silence};\n",
        clock_seconds(melee_end)?,
        clock_seconds(ranged_extra)?,
        clock_seconds(flag_every)?,
        minute_seconds(decay)?,
        minute_seconds(floor)?,
    ))
}

fn text<'a>(notes: &'a Kv, key: &str) -> Result<&'a str, String> {
    match notes.get("patch").and_then(|rows| rows.get(key)) {
        Some(Kv::Text(row)) => Ok(row),
        _ => Err(format!("patch notes missing {key}")),
    }
}

fn last_numbered_word<'a>(row: &'a str, prefix: &str) -> Result<&'a str, String> {
    row.rsplit_once(prefix)
        .and_then(|(_, text)| text.split_ascii_whitespace().next())
        .ok_or_else(|| format!("patch note requires {prefix:?} followed by a value: {row:?}"))
}

fn clock_seconds(clock: &str) -> Result<u32, String> {
    let bad = || format!("patch note requires a minute:second clock, got {clock:?}");
    let (minutes, seconds) = clock.split_once(':').ok_or_else(bad)?;
    let whole = minute_seconds(minutes)?;
    let seconds: u32 = seconds.parse().map_err(|_| bad())?;
    if seconds >= 60 {
        return Err(bad());
    }
    whole.checked_add(seconds).ok_or_else(bad)
}

fn minute_seconds(minutes: &str) -> Result<u32, String> {
    let (whole, half) = match minutes.strip_suffix(".5") {
        Some(whole) => (whole, 30),
        None => (minutes, 0),
    };
    whole
        .parse::<u32>()
        .ok()
        .and_then(|whole| whole.checked_mul(60))
        .and_then(|seconds| seconds.checked_add(half))
        .ok_or_else(|| format!("invalid minutes in patch note: {minutes:?}"))
}

fn siege_row(row: &str) -> Result<(u32, u32, u32), String> {
    let bad = || format!("invalid siege wave row: {row:?}");
    let (clock, rest) = row.split_once(['-', '+']).ok_or_else(bad)?;
    let (_, interval) = rest.split_once("Every ").ok_or_else(bad)?;
    let (minutes, rest) = interval.split_once(" minutes, ").ok_or_else(bad)?;
    let (count, _) = rest.split_once(" siege creep").ok_or_else(bad)?;
    Ok((
        clock_seconds(clock)?,
        minute_seconds(minutes)?,
        count.parse().map_err(|_| bad())?,
    ))
}
